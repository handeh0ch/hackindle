// Generate the device table from the same Node Unicode data used by the server.
import { writeFileSync } from 'node:fs';
const mapping = [], cased = [], ignorable = [];
const ranges = values => {
  const out = [];
  for (const value of values) {
    const last = out.at(-1);
    if (last && last[1] + 1 === value) last[1] = value;
    else out.push([value, value]);
  }
  return out;
};
for (let n = 0; n <= 0x10ffff; n++) {
  if (n >= 0xd800 && n <= 0xdfff) continue;
  const char = String.fromCodePoint(n), lower = char.toLowerCase();
  if (lower !== char) mapping.push(`[${n}]={${[...lower].map(c => c.codePointAt(0)).join(',')}}`);
  if (/\p{Cased}/u.test(char)) cased.push(n);
  if (/\p{Case_Ignorable}/u.test(char)) ignorable.push(n);
}
const format = values => ranges(values).map(([a, b]) => `{${a},${b}}`).join(',');
writeFileSync(new URL('../plugin/unicode_data.lua', import.meta.url), `-- Generated by scripts/generate-unicode-casing.js; Node Unicode ${process.versions.unicode}.\nreturn {version=${JSON.stringify(process.versions.unicode)},map={${mapping.join(',')}},cased={${format(cased)}},ignorable={${format(ignorable)}}}\n`);
