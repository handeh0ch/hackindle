package.path = "plugin/?.lua;" .. package.path
local reading = require("reading")
local function compare(a, b) return a - b end
local function measure(a, b) return b - a end
local ledger = reading.new(compare, measure)
local pieces = ledger:credit("source-a", "2026-01-01", 0, 10)
assert(#pieces == 1 and pieces[1].first == 0 and pieces[1].last == 10 and pieces[1].characters == 10)
pieces = ledger:credit("source-a", "2026-01-01", 5, 15)
assert(#pieces == 1 and pieces[1].first == 10 and pieces[1].characters == 5)
assert(#ledger:credit("source-a", "2026-01-01", 3, 8) == 0)
assert(#ledger:credit("source-a", "2026-01-01", 100, 110) == 1)
pieces = ledger:credit("source-a", "2026-01-01", 0, 110)
assert(#pieces == 1 and pieces[1].first == 15 and pieces[1].last == 100)
assert(#ledger:credit("source-a", "2026-01-02", 0, 10) == 1)
assert(#ledger:credit("source-b", "2026-01-01", 0, 10) == 1)
assert(not pcall(function() ledger:credit("source-a", "2026-01-01", 10, 10) end))
print("reading assertions passed")
local reading = require("reading")
assert(reading.count("a é🙂é") == 6)
assert(not pcall(reading.count, "\192\128"))
assert(not pcall(reading.count, "\237\160\128"))
assert(not pcall(reading.count, "\244\144\128\128"))
assert(not pcall(reading.count, "\226\130"))
local restored = reading.new(compare, measure, ledger.days)
assert(#restored:credit("source-a", "2026-01-01", 0, 10) == 0)
local invalid = reading.new(compare, function() return 1.5 end)
assert(not pcall(function() invalid:credit("s", "d", 0, 1) end))
